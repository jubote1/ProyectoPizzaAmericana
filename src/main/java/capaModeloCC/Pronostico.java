package capaModeloCC;

public class Pronostico {

    private int idPartido;
    private String nombreCliente;
    private String telefono;
    private int idTienda;
    private String numeroFactura;
    private int marcadorPais1;
    private int marcadorPais2;
	public int getIdPartido() {
		return idPartido;
	}
	public void setIdPartido(int idPartido) {
		this.idPartido = idPartido;
	}
	public String getNombreCliente() {
		return nombreCliente;
	}
	public void setNombreCliente(String nombreCliente) {
		this.nombreCliente = nombreCliente;
	}
	public String getTelefono() {
		return telefono;
	}
	public void setTelefono(String telefono) {
		this.telefono = telefono;
	}
	public int getIdTienda() {
		return idTienda;
	}
	public void setIdTienda(int idTienda) {
		this.idTienda = idTienda;
	}
	public String getNumeroFactura() {
		return numeroFactura;
	}
	public void setNumeroFactura(String numeroFactura) {
		this.numeroFactura = numeroFactura;
	}
	public int getMarcadorPais1() {
		return marcadorPais1;
	}
	public void setMarcadorPais1(int marcadorPais1) {
		this.marcadorPais1 = marcadorPais1;
	}
	public int getMarcadorPais2() {
		return marcadorPais2;
	}
	public void setMarcadorPais2(int marcadorPais2) {
		this.marcadorPais2 = marcadorPais2;
	}

}