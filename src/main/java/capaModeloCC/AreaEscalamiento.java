public class AreaEscalamiento {
	private int idarea;
	private String area;
	private String correos;
	private String inicio_horario;
	private String final_horario;
	
	public int getIdarea() {
		return idarea;
	}
	public void setIdarea(int idarea) {
		this.idarea = idarea;
	}
	public String getArea() {
		return area;
	}
	public void setArea(String area) {
		this.area = area;
	}
	public String getCorreos() {
		return correos;
	}
	public void setCorreos(String correos) {
		this.correos = correos;
	}
	public String getInicio_horario() {
		return inicio_horario;
	}
	public void setInicio_horario(String inicio_horario) {
		this.inicio_horario = inicio_horario;
	}
	public String getFinal_horario() {
		return final_horario;
	}
	public void setFinal_horario(String final_horario) {
		this.final_horario = final_horario;
	}
	
    public AreaEscalamiento (){
    	
    }
    }
